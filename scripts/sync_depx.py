#!/usr/bin/env python3
"""Refresh the depx packages used by the in-process dependency scanner."""

import argparse
import hashlib
import json
from pathlib import Path
import re
import subprocess
import tempfile


MODULE = "github.com/projectdiscovery/depx"
VERSION = "v0.1.1"
ROOT = Path(__file__).resolve().parents[1]
DEST = ROOT / "internal/depxbridge/third_party/depx"
IMPORT_PREFIX = "github.com/mr-pmillz/gogatoz/internal/depxbridge/third_party/depx"
HEADER = "// Code generated by scripts/sync_depx.py; DO NOT EDIT.\n\n"
PATCHES = ROOT / "scripts/depx_patches"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="verify the snapshot without modifying it")
    args = parser.parse_args()
    metadata = json.loads(subprocess.check_output(
        ["go", "mod", "download", "-json", f"{MODULE}@{VERSION}"],
        cwd=ROOT, text=True,
    ))
    source = Path(metadata["Dir"])
    pending = ["audit", "config", "intel", "registry"]
    packages = set()
    files = {}
    while pending:
        package = pending.pop()
        if package in packages:
            continue
        packages.add(package)
        sources = sorted((source / "internal" / package).glob("*.go"))
        if not sources:
            raise RuntimeError(f"upstream package has no Go files: {package}")
        for path in sources:
            if path.name.endswith("_test.go"):
                continue
            content = path.read_text(encoding="utf-8")
            pending.extend(re.findall(
                r'"github.com/projectdiscovery/depx/internal/([^\"]+)"', content,
            ))
            # Resolve Go's internal import boundary within this module. The
            # upstream code and build constraints otherwise remain unchanged.
            files[Path(package) / path.name] = HEADER + content.replace(
                MODULE + "/internal/", IMPORT_PREFIX + "/",
            )

    patches = sorted(PATCHES.glob("*.patch"))
    # Apply to a staging directory first. An incompatible upstream update must
    # fail without leaving a partially refreshed source snapshot in the repo.
    with tempfile.TemporaryDirectory(prefix="gogatoz-depx-sync-") as directory:
        stage = Path(directory)
        for relative, content in files.items():
            target = stage / relative
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(content, encoding="utf-8", newline="\n")
        for patch in patches:
            subprocess.run(["git", "apply", str(patch)], cwd=stage, check=True)
        files = {path.relative_to(stage): path.read_text(encoding="utf-8") for path in stage.rglob("*.go")}

    files[Path("LICENSE")] = (source / "LICENSE").read_text(encoding="utf-8")
    files[Path("UPSTREAM.json")] = json.dumps({
        "module": MODULE,
        "version": VERSION,
        "sum": metadata["Sum"],
        "go_mod_sum": metadata["GoModSum"],
        "packages": sorted(packages),
        "patches": [{
            "path": str(patch.relative_to(ROOT)),
            "sha256": hashlib.sha256(patch.read_bytes()).hexdigest(),
        } for patch in patches],
    }, indent=2) + "\n"
    stale = [path for path in DEST.rglob("*.go") if path.relative_to(DEST) not in files]
    if args.check:
        changed = [str(path.relative_to(ROOT)) for path in stale]
        for relative, content in sorted(files.items()):
            target = DEST / relative
            if not target.is_file() or target.read_text(encoding="utf-8") != content:
                changed.append(str(target.relative_to(ROOT)))
        if changed:
            parser.exit(1, "depx snapshot differs; run python3 scripts/sync_depx.py:\n" + "\n".join(changed) + "\n")
        print(f"Verified depx snapshot at {VERSION}")
        return
    for path in stale:
        path.unlink()
    for relative, content in sorted(files.items()):
        target = DEST / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(content, encoding="utf-8", newline="\n")
    print(f"Synced {len(files) - 2} Go files from {MODULE}@{VERSION}")


if __name__ == "__main__":
    main()

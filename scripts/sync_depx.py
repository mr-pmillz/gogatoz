#!/usr/bin/env python3
"""Refresh the depx packages used by the in-process dependency scanner."""

import json
from pathlib import Path
import re
import shutil
import subprocess


MODULE = "github.com/projectdiscovery/depx"
VERSION = "v0.1.1"
ROOT = Path(__file__).resolve().parents[1]
DEST = ROOT / "internal/depxbridge/third_party/depx"
IMPORT_PREFIX = "github.com/mr-pmillz/gogatoz/internal/depxbridge/third_party/depx"
HEADER = "// Code generated by scripts/sync_depx.py; DO NOT EDIT.\n\n"


def main():
    metadata = json.loads(subprocess.check_output(
        ["go", "mod", "download", "-json", f"{MODULE}@{VERSION}"],
        cwd=ROOT, text=True,
    ))
    source = Path(metadata["Dir"])
    pending = ["audit", "config", "intel", "registry"]
    packages = set()
    files = {}
    while pending:
        package = pending.pop()
        if package in packages:
            continue
        packages.add(package)
        for path in sorted((source / "internal" / package).glob("*.go")):
            if path.name.endswith("_test.go"):
                continue
            content = path.read_text()
            pending.extend(re.findall(
                r'"github.com/projectdiscovery/depx/internal/([^\"]+)"', content,
            ))
            # Resolve Go's internal import boundary within this module. The
            # upstream code and build constraints otherwise remain unchanged.
            files[Path(package) / path.name] = HEADER + content.replace(
                MODULE + "/internal/", IMPORT_PREFIX + "/",
            )

    for path in DEST.rglob("*.go"):
        if path.relative_to(DEST) not in files:
            path.unlink()
    for relative, content in sorted(files.items()):
        target = DEST / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(content)
    shutil.copyfile(source / "LICENSE", DEST / "LICENSE")
    (DEST / "UPSTREAM.json").write_text(json.dumps({
        "module": MODULE,
        "version": VERSION,
        "sum": metadata["Sum"],
        "go_mod_sum": metadata["GoModSum"],
        "packages": sorted(packages),
    }, indent=2) + "\n")
    print(f"Synced {len(files)} files from {MODULE}@{VERSION}")


if __name__ == "__main__":
    main()
